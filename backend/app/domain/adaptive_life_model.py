from __future__ import annotations

import math
from dataclasses import dataclass, field
from datetime import datetime
from typing import List


VALID_SEVERITIES = {"low", "medium", "high", "critical"}


@dataclass
class LifeSignal:
    """Observed life-system signal used by the Adaptive Life Operating System."""

    signal_id: str
    signal_type: str
    severity: str
    confidence: float
    source_engine: str
    description: str
    timestamp: datetime = field(default_factory=datetime.utcnow)

    def __post_init__(self) -> None:
        self.signal_id = _required_text(self.signal_id, "signal_id")
        self.signal_type = _required_text(self.signal_type, "signal_type")
        self.source_engine = _required_text(self.source_engine, "source_engine")
        self.description = _required_text(self.description, "description")
        self.severity = _severity(self.severity)
        self.confidence = _bounded_float(self.confidence, "confidence", 0.0, 1.0)


@dataclass
class Opportunity:
    """Ranked opportunity detected from goals, tasks, capacity, and behavior."""

    opportunity_id: str
    category: str
    impact_score: float
    confidence: float
    recommended_action: str
    expected_benefit: str

    def __post_init__(self) -> None:
        self.opportunity_id = _required_text(self.opportunity_id, "opportunity_id")
        self.category = _required_text(self.category, "category")
        self.recommended_action = _required_text(self.recommended_action, "recommended_action")
        self.expected_benefit = _required_text(self.expected_benefit, "expected_benefit")
        self.impact_score = _bounded_float(self.impact_score, "impact_score", 0.0, 100.0)
        self.confidence = _bounded_float(self.confidence, "confidence", 0.0, 1.0)


@dataclass
class RiskAlert:
    """Risk alert surfaced by the Adaptive Life Operating System."""

    alert_id: str
    risk_type: str
    severity: str
    confidence: float
    affected_goals: List[str]
    recommended_mitigation: str

    def __post_init__(self) -> None:
        self.alert_id = _required_text(self.alert_id, "alert_id")
        self.risk_type = _required_text(self.risk_type, "risk_type")
        self.severity = _severity(self.severity)
        self.confidence = _bounded_float(self.confidence, "confidence", 0.0, 1.0)
        if not isinstance(self.affected_goals, list) or any(not isinstance(goal_id, str) for goal_id in self.affected_goals):
            raise ValueError("affected_goals must be a list of strings.")
        self.affected_goals = sorted(set(self.affected_goals))
        self.recommended_mitigation = _required_text(self.recommended_mitigation, "recommended_mitigation")


@dataclass
class AdaptiveRecommendation:
    """Recommendation generated by ALOS. It is advisory only."""

    recommendation_id: str
    category: str
    priority: int
    reason: str
    action: str
    expected_outcome: str

    def __post_init__(self) -> None:
        self.recommendation_id = _required_text(self.recommendation_id, "recommendation_id")
        self.category = _required_text(self.category, "category")
        self.reason = _required_text(self.reason, "reason")
        self.action = _required_text(self.action, "action")
        self.expected_outcome = _required_text(self.expected_outcome, "expected_outcome")
        if not isinstance(self.priority, int) or isinstance(self.priority, bool) or self.priority <= 0:
            raise ValueError("priority must be a positive integer.")


def _required_text(value: object, field_name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{field_name} must be a non-empty string.")
    return value.strip()


def _severity(value: object) -> str:
    if not isinstance(value, str):
        raise ValueError("severity must be low, medium, high, or critical.")
    normalized = value.strip().lower()
    if normalized not in VALID_SEVERITIES:
        raise ValueError("severity must be low, medium, high, or critical.")
    return normalized


def _bounded_float(value: object, field_name: str, minimum: float, maximum: float) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        raise ValueError(f"{field_name} must be numeric.") from None
    if not math.isfinite(number):
        raise ValueError(f"{field_name} must be finite.")
    return max(minimum, min(maximum, number))
